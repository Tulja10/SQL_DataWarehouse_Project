-- EXPLORATORY DATA ANALYSIS ON products, customers and sales...

-- DATABSE EXPLORATION

SELECT * FROM INFORMATION_SCHEMA.TABLES;

SELECT * FROM INFORMATION_SCHEMA.COLUMNS;

-- DIMENSIONS EXPLORATION

-- all countries from where customers come from
SELECT DISTINCT country FROM gold.dim_customers;

-- all cateories, subcategories and products available
SELECT DISTINCT category, subcategory, product_name 
FROM gold.dim_products
ORDER BY category, subcategory;

-- DATE EXPLORATION

-- first and last order dates
SELECT MIN(order_date) AS first_order_date,
	   MAX(order_date) AS last_order_date
FROM gold.fact_sales;

--timespan of business
SELECT
	EXTRACT(YEAR FROM MAX(order_date))-EXTRACT(YEAR FROM MIN(order_date)) AS order_range_years
FROM gold.fact_sales;

-- oldest and youngest customers
SELECT EXTRACT(YEAR FROM AGE(current_date, MIN(birthdate))) AS oldest_cust_age,
	   EXTRACT(YEAR FROM AGE(current_date, MAX(birthdate))) AS youngest_cust_age
FROM gold.dim_customers;

-- MEASURES EXPLORATION( business metrices)

--total sales
SELECT SUM(sales) AS total_sales
FROM gold.fact_sales

--total items sold
SELECT SUM(quantity) AS items_sold
FROM gold.fact_sales;

-- average selling price
SELECT ROUND(AVG(price),2) AS avg_price
FROM gold.fact_sales;

--total number of orders
SELECT COUNT(DISTINCT order_no) AS total_orders
FROM gold.fact_sales;

-- total number of products
SELECT COUNT( DISTINCT product_name) AS total_products
FROM gold.dim_products;

--total number of customers
SELECT COUNT( DISTINCT cutomer_key) AS total_customers
FROM gold.dim_customers;

-- total number of customers that have placed an order
SELECT COUNT( DISTINCT customer_key) AS total_customers_with_order
FROM gold.fact_sales;

-- MAGNITUDE ANALYSIS( measures by dimension)

-- total customers by countries
SELECT country, COUNT(customer_key) AS customers
FROM gold.dim_customers
GROUP BY country
ORDER BY customers DESC;

-- total customers by gender
SELECT gender, COUNT(customer_key) AS customers
FROM gold.dim_customers
GROUP BY gender
ORDER BY customers DESC;

-- total products by category
SELECT category, COUNT(product_key) AS total_products
FROM gold.dim_products
GROUP BY category
ORDER BY total_products DESC;

-- average costs in each category
SELECT category, ROUND(AVG(cost),2) AS avg_cost
FROM gold.dim_products
GROUP BY category
ORDER BY avg_cost;

-- total revenue generated for each category 
SELECT category, SUM(sales) AS revenue
FROM gold.fact_sales s
LEFT JOIN gold.dim_products p
ON p.product_key = s.product_key
GROUP BY p.category
ORDER BY revenue DESC;

-- total revenue generated by each customer
SELECT c.customer_id,
	   c.first_name,
	   c.last_name,
	   SUM(sales) AS revenue
FROM gold.fact_sales s
LEFT JOIN gold.dim_customers c
ON c.customer_key = s.customer_key
GROUP BY c.customer_id,c.first_name,c.last_name
ORDER BY revenue DESC;

-- distribution of sold items across countries
SELECT c.country, SUM(quantity) AS items_sold
FROM gold.dim_customers c
LEFT JOIN gold.fact_sales s
ON c.customer_key = s.customer_key
GROUP BY c.country
ORDER BY items_sold DESC;

-- RANKING ANALYSIS

-- top 10 products with highest revenue
SELECT p.product_name, SUM(sales) AS revenue
FROM gold.fact_sales s
LEFT JOIN gold.dim_products p
ON p.product_key = s.product_key
GROUP BY p.product_name
ORDER BY revenue DESC
LIMIT 10;

-- 5 worst performing products
SELECT p.product_name, SUM(sales) AS revenue
FROM gold.fact_sales s
LEFT JOIN gold.dim_products p
ON p.product_key = s.product_key
GROUP BY p.product_name
ORDER BY revenue 
LIMIT 5;

-- top 10 customers who generated highest revenue 
SELECT c.customer_id,
	   c.first_name,
	   c.last_name,
	   SUM(sales) AS revenue
FROM gold.fact_sales s
LEFT JOIN gold.dim_customers c
ON c.customer_key = s.customer_key
GROUP BY c.customer_id,c.first_name,c.last_name
ORDER BY revenue DESC
LIMIT 10;

-- customers with least orders
SELECT c.customer_id,
	   c.first_name,
	   c.last_name,
	   COUNT( DISTINCT order_no) AS unique_orders
FROM gold.fact_sales s
LEFT JOIN gold.dim_customers c
ON c.customer_key = s.customer_key
GROUP BY c.customer_id,c.first_name,c.last_name
HAVING COUNT( DISTINCT order_no)<=1;




































